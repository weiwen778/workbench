import { showNavGroup } from './navigation.mjs'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import { chromium } from 'playwright'

const base = process.env.WB_BASE || 'http://127.0.0.1:18746'
assert.ok(['127.0.0.1', 'localhost', '[::1]'].includes(new URL(base).hostname))
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined })
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } })
const page = await context.newPage()
const errors = []
page.on('pageerror', e => errors.push(e.message))
async function api(path, body, method = 'POST') {
  const csrf = (await context.cookies()).find(c => c.name === 'wb_csrf')?.value || ''
  const response = await context.request.fetch(base + '/api/v1' + path, { method, headers: { 'X-CSRF-Token': csrf }, data: body })
  assert.ok(response.ok(), await response.text())
  return response.json()
}
